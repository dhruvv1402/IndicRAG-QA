"""Regenerate every committed report from cached artefacts.

`docs/PRD.md` NFR-6: every reported table must be reproducible by one command.
That is not bureaucracy -- it is what stops the numbers in the paper drifting away
from the numbers in the repository. A table that can only be regenerated by
remembering which of eleven scripts produced it will, eventually, disagree with
its own source.

Each stage is independent and degrades rather than fails. A stage whose inputs
are missing is skipped with a reason and the rest still run, because on a CPU-only
machine some artefacts legitimately do not exist yet -- the LaBSE embeddings, the
generation cache -- and a harness that refuses to produce anything until
everything is present is one nobody runs.

The provenance banner is not decoration. Every report carries whether it was
built from the human-verified gold set or from synthetic probes, and how many
items were unverified. A preliminary number that ends up in a paper because
nothing on the page said it was preliminary is the specific failure this guards
against.
"""

from __future__ import annotations

import datetime
from collections.abc import Callable, Sequence
from dataclasses import dataclass, field
from pathlib import Path

from ..config import get_settings
from ..models import Passage, QAItem, read_jsonl


@dataclass
class StageResult:
    name: str
    path: Path | None = None
    lines: int = 0
    skipped: str = ""

    @property
    def ok(self) -> bool:
        return not self.skipped


@dataclass
class RunSummary:
    stages: list[StageResult] = field(default_factory=list)

    def add(self, stage: StageResult) -> None:
        self.stages.append(stage)

    def format(self) -> list[str]:
        out = ["", "EVAL ALL -- summary", "-" * 78]
        for s in self.stages:
            if s.ok:
                out.append(f"  ok       {s.name:<28} {s.lines:>4} lines -> {s.path}")
            else:
                out.append(f"  skipped  {s.name:<28} {s.skipped}")
        done = sum(1 for s in self.stages if s.ok)
        out += ["", f"  {done}/{len(self.stages)} stages produced a report."]
        return out


#: `annotator` prefix for a verification done by a model rather than a person.
MODEL_ANNOTATOR_PREFIX = "model:"


def verification_label(items: Sequence[QAItem]) -> str:
    """One word for a report header: who checked these items, if anyone."""
    if not items or not all(i.verified for i in items):
        return "UNVERIFIED" if not any(i.verified for i in items) else "partly verified"
    if all(i.annotator.startswith(MODEL_ANNOTATOR_PREFIX) for i in items):
        return "model-verified"
    return "verified"


def provenance(items: Sequence[QAItem], source: str) -> list[str]:
    """The banner every report carries, stating what the numbers rest on."""
    total = len(items)
    verified = sum(1 for i in items if i.verified)
    answerable = sum(1 for i in items if i.answerable)
    stamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")

    by_model = sum(1 for i in items if i.verified and i.annotator.startswith(MODEL_ANNOTATOR_PREFIX))
    lines = [
        f"Generated: {stamp}",
        f"Source:    {source}",
        f"Items:     {total} ({answerable} answerable, {total - answerable} unanswerable)",
        f"Verified:  {verified}/{total}"
        + (f"  ({verified - by_model} by a person, {by_model} by a model)" if by_model else ""),
    ]
    if by_model:
        # Said on every report, not only in the paper: a number copied out of
        # a report must not lose the fact that no person checked its items.
        lines += [
            "",
            "MODEL-VERIFIED. Verification of these items was done by a language-model",
            "pass (annotator 'model:...'), not by a person as PRD §6.5 specifies; see",
            "paper §III-D for the procedure and its agreement figures.",
        ]
    if verified < total:
        lines += [
            "",
            "PRELIMINARY. Items that have not been through human verification are",
            "included in these numbers. PRD §10.2 excludes unverified items from any",
            "reported result, so nothing here may be quoted as a gold-set figure.",
        ]
    return lines + [""]


def _write(path: Path, lines: Sequence[str]) -> StageResult:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return StageResult(name=path.stem, path=path, lines=len(lines))


def run_all(
    out_dir: Path,
    *,
    gold_path: Path,
    progress: Callable[[str], None] | None = None,
    include_qa: bool = False,
) -> RunSummary:
    """Regenerate the corpus, retrieval, answerability and error reports."""
    say = progress or (lambda _m: None)
    cfg = get_settings()
    out_dir = Path(out_dir)
    summary = RunSummary()

    passages = list(read_jsonl(cfg.passages_path, Passage))
    if not passages:
        summary.add(StageResult("all", skipped="no passages; run `corpus segment`"))
        return summary

    items = list(read_jsonl(gold_path, QAItem)) if Path(gold_path).exists() else []
    source = str(gold_path) if items else "none"
    banner = provenance(items, source) if items else []

    # --- corpus ---------------------------------------------------------------
    from .report import format_corpus_stats

    say("corpus stats")
    summary.add(
        _write(out_dir / "report-corpus.txt", [f"Generated: {datetime.datetime.now():%Y-%m-%d %H:%M}", ""] + format_corpus_stats(passages))
    )

    # --- retrieval ------------------------------------------------------------
    say("retrieval")
    try:
        from .report import format_by_slice, format_paired, format_retrieval
        from .run import run_retrieval

        probes = list(read_jsonl(out_dir / "probes.jsonl", QAItem))
        eval_items = [i for i in items if i.answerable and i.gold_passage_ids] or probes
        eval_source = source if eval_items is not probes else "synthetic probes"
        if not eval_items:
            raise FileNotFoundError("no answerable items and no probes")

        reports, skipped = run_retrieval(passages, eval_items, progress=lambda m: None)
        lines = provenance(eval_items, eval_source)
        lines += format_retrieval(reports) + [""] + format_by_slice(reports)
        lines += [""] + format_paired(reports, baseline="BM25")
        if skipped:
            lines += ["", "NOT EVALUATED", "-" * 78] + [f"  {s}" for s in skipped]
        summary.add(_write(out_dir / "report-retrieval.txt", lines))
    except Exception as exc:  # noqa: BLE001 -- reported, never swallowed
        summary.add(StageResult("report-retrieval", skipped=f"{type(exc).__name__}: {exc}"))

    # --- errors ---------------------------------------------------------------
    say("error analysis")
    try:
        from .errors import ErrorCase, format_errors

        cases = [ErrorCase.from_dict(d) for d in read_jsonl(out_dir / "errors.jsonl")]
        if not cases:
            raise FileNotFoundError("no errors.jsonl; run `eval errors` first")
        summary.add(
            _write(out_dir / "report-errors.txt", banner + format_errors(cases, passages))
        )
    except Exception as exc:  # noqa: BLE001
        summary.add(StageResult("report-errors", skipped=f"{type(exc).__name__}: {exc}"))

    # --- answerability --------------------------------------------------------
    say("answerability")
    try:
        from .answerability import (
            feature_separation,
            format_answerability,
            format_feature_separation,
            format_separation,
            format_separation_across_methods,
            format_tau_sweep,
            run_answerability,
            separation_across_methods,
            tau_sweep,
        )

        if not any(not i.answerable for i in items):
            raise FileNotFoundError(
                "no unanswerable items; answerability cannot be measured against a "
                "set that is entirely answerable"
            )
        result, meta = run_answerability(passages, items, progress=lambda m: None)
        lines = banner + [
            f"tau fitted on {len(meta['dev'])} items (F1={meta['dev_f1']:.3f}); "
            f"reported on {len(meta['test'])} held out.",
            "",
        ]
        lines += format_answerability(result)
        lines += [""] + format_separation(meta["scores"], meta["labels"], method=meta["method"])
        lines += [""] + format_separation_across_methods(
            separation_across_methods(passages, items)
        )
        lines += [""] + format_feature_separation(
            feature_separation(meta["features"], meta["labels"]), method=meta["method"]
        )
        lines += [""] + format_tau_sweep(tau_sweep(meta["features"], meta["labels"]))
        summary.add(_write(out_dir / "report-answerability.txt", lines))
    except Exception as exc:  # noqa: BLE001
        summary.add(StageResult("report-answerability", skipped=f"{type(exc).__name__}: {exc}"))

    # --- module 4 -------------------------------------------------------------
    if include_qa:
        summary.add(
            StageResult(
                "report-qa",
                skipped="run `indicrag eval qa --report evals/report-qa.txt` directly; "
                "it needs a generator and is not cheap enough to fold in here",
            )
        )

    return summary
